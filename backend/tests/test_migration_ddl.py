"""Regression tests for explicit, reversible Alembic schema DDL."""

from pathlib import Path


def test_initial_revision_uses_explicit_operations():
    revision = (
        Path(__file__).parents[1]
        / "migrations"
        / "versions"
        / "20260820_01_initial_schema.py"
    ).read_text(encoding="utf-8")
    assert "Base.metadata.create_all" not in revision
    assert "Base.metadata.drop_all" not in revision
    assert "op.create_table(" in revision
    assert "op.drop_table(" in revision


def test_initial_revision_is_not_implicitly_autogenerated():
    revision = (
        Path(__file__).parents[1]
        / "migrations"
        / "versions"
        / "20260820_01_initial_schema.py"
    ).read_text(encoding="utf-8")
    assert "metadata.create_all" not in revision
    assert "metadata.drop_all" not in revision
